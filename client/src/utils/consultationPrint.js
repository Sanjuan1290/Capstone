const escapeHtml = (value) => String(value ?? '')
  .replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;')
  .replace(/"/g, '&quot;').replace(/'/g, '&#039;')

const line = (label, value) => value ? `<div class="line"><span>${escapeHtml(label)}</span><strong>${escapeHtml(value)}</strong></div>` : ''

