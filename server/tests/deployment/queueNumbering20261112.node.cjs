const test=require('node:test'),assert=require('node:assert/strict'),fs=require('node:fs')
const {runQueueNumberingStatement,verifyQueueNumberingIndexes}=require('../../utils/queueNumberingSchema')
const {queueSchemaFixture}=require('../helpers/queueSchemaFixture.cjs')
const sql=fs.readFileSync(require.resolve('../../db/migrations/2026-11-12-queue-daily-department-numbers.sql'),'utf8')
const statements=sql.split('\n').filter(line=>line.startsWith('ALTER')).map(line=>line.replace(/;$/,''))
test('partial DDL resumes safely, replaces the global index only after its replacement, and reruns without duplicate keys',async()=>{
 const db=queueSchemaFixture()
 await assert.rejects(runQueueNumberingStatement(db,statements[2]),/required before removing/)
 await runQueueNumberingStatement(db,statements[0])
 for(const statement of statements)await runQueueNumberingStatement(db,statement)
 await verifyQueueNumberingIndexes(db)
 assert.equal(db.commands.length,3)
 for(const statement of statements)await runQueueNumberingStatement(db,statement)
 await verifyQueueNumberingIndexes(db);assert.equal(db.commands.length,3)
 assert.doesNotMatch(sql,/\b(?:DELETE|UPDATE|TRUNCATE)\b/i)
})
test('unexpected existing index definitions fail before changing the constraint',async()=>{
 const db=queueSchemaFixture();db.indexes.set('uniq_queue_branch_doctor_day_number',{columns:['branch_id'],unique:false})
 await assert.rejects(runQueueNumberingStatement(db,statements[0]),/Incompatible queue index/)
 assert.equal(db.commands.length,0);assert.ok(db.indexes.has('uniq_queue_doctor_day_number'))
})
