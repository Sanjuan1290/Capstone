const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const { collectBranchReportQueries, verifyBranchReportsSql } = require('../../scripts/verifyBranchReportsSql')

test('branch Reports query contract is generated by the actual HTTP handler, including on an empty clinic', async () => {
  const queries = await collectBranchReportQueries()
  assert.equal(queries.length, 20)
  for (const { sql, params } of queries) {
    assert.match(sql, /^SELECT\b/i)
    if (!sql.includes('SELECT report_footer')) {
      assert.match(sql, /branch_id\s*=\s*\?|(?:br|i|b|il|a)\.branch_id/)
      assert.ok(params.includes(1), `Reports query missing branch parameter: ${sql.slice(0, 100)}`)
    }
  }
})

test('stock valuation never uses ambiguous expiry/quantity columns after joining inventory and batches', async () => {
  const queries = await collectBranchReportQueries()
  const valuation = queries.find(({ sql }) => sql.includes('batches_without_cost'))
  assert.ok(valuation, 'Missing inventory batch valuation query')
  assert.match(valuation.sql, /b\.expiration_date\s*<\s*\?/)
  assert.match(valuation.sql, /b\.expiration_date\s+BETWEEN\s+\?\s+AND\s+\?/)
  assert.match(valuation.sql, /b\.quantity\s*\*\s*COALESCE\(b\.unit_cost/)
  assert.doesNotMatch(valuation.sql, /(?<!\.)\bexpiration_date\s*(?:<|BETWEEN)/i)
})

test('deployment preflight EXPLAINs every Reports query without executing writes', async () => {
  const calls = []
  const db = { query: async (sql, args) => { calls.push({ sql, args }); return [[]] } }
  assert.equal(await verifyBranchReportsSql(db), 20)
  assert.equal(calls.length, 20)
  for (const { sql } of calls) assert.match(sql, /^EXPLAIN SELECT\b/)
})

test('reports preflight rejects bad SQL with a numbered, actionable error', async () => {
  let seen = 0
  const db = { query: async () => {
    if (++seen === 19) throw Object.assign(new Error('Column expiration_date in field list is ambiguous'), { code: 'ER_NON_UNIQ_ERROR' })
    return [[]]
  } }
  await assert.rejects(verifyBranchReportsSql(db), /Branch Reports query 19\/20 failed SQL validation \(ER_NON_UNIQ_ERROR\)/)
})

test('report screen aborts stale requests and displays only the active response', () => {
  const root = path.resolve(__dirname, '../../../')
  const service = fs.readFileSync(path.join(root, 'client/src/services/admin.service.js'), 'utf8')
  const page = fs.readFileSync(path.join(root, 'client/src/pages/adminPage/Admin_Reports.jsx'), 'utf8')
  assert.match(service, /getReports\s*=\s*\(params = \{\}, options = \{\}\)/)
  assert.match(page, /activeReportRequest\.current\?\.abort\(\)/)
  assert.match(page, /controller\.signal\.aborted/)
  assert.match(page, /signal: controller\.signal/)
})


